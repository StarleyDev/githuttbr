# Checkout flow

How a cart becomes a charge: total the lines, then hand the amount to payments.

## Totalling the cart

- A cart is a list of lines, each a SKU, a quantity and a unit price. — \`src/checkout/cart.ts\`
- The total is the sum of quantity times price over every line. — \`src/checkout/cart.ts\`

## Submitting

- Submitting totals the lines and charges that amount with the customer's card token, returning the charge's id. — \`src/checkout/submit.ts\`

## See also

- [Payments](payments.md)

[← Index](README.md)
