# The wiki was generated on someone else's machine and exported, but not yet
# committed — the state a fresh clone of a teammate's work, or a reinstall,
# leaves behind. This machine has no stored copy, so the Wiki page must read
# the folder. The export is stamped with HEAD's sha, so it reads as current.
#
# Verify:
#   • ⌘K → Wiki ⇒ three pages (Overview, Checkout flow, Payments), the
#     "Read from docs/wiki in the repository" line, no "outdated" banner.
#   • Overview ⇒ the stack card (React, Stripe, Vitest), from the index's data.
#   • The folder icon beside Export ⇒ a picker opening on docs/wiki.
#   • Delete ⇒ a confirm; it removes the four exported files and leaves
#     docs/wiki/NOTES.md, which the export did not write.
R="$ROOT/repo-wiki"
new_repo "$R"

at() { GIT_AUTHOR_DATE="$1" GIT_COMMITTER_DATE="$1" git -C "$R" commit -qm "$2"; }

mkdir -p "$R/src/checkout" "$R/src/payments"
cat > "$R/README.md" <<'EOT'
# Corner shop
A storefront: browse, add to the cart, check out with a card.
EOT
cat > "$R/package.json" <<'EOT'
{
  "name": "corner-shop",
  "private": true,
  "dependencies": { "react": "^19.0.0", "react-dom": "^19.0.0", "stripe": "^17.0.0" },
  "devDependencies": { "vitest": "^3.0.0", "typescript": "^5.6.0" }
}
EOT
cat > "$R/src/checkout/cart.ts" <<'EOT'
export interface Line { sku: string; qty: number; price: number }

export function total(lines: Line[]): number {
  return lines.reduce((sum, l) => sum + l.qty * l.price, 0)
}
EOT
cat > "$R/src/checkout/submit.ts" <<'EOT'
import { total, type Line } from './cart'
import { charge } from '../payments/charge'

export async function submit(lines: Line[], token: string): Promise<string> {
  return charge(total(lines), token)
}
EOT
cat > "$R/src/payments/charge.ts" <<'EOT'
import Stripe from 'stripe'

const stripe = new Stripe(process.env.STRIPE_KEY ?? '')

export async function charge(amount: number, token: string): Promise<string> {
  const intent = await stripe.paymentIntents.create({ amount, currency: 'usd', payment_method: token, confirm: true })
  return intent.id
}
EOT
git -C "$R" add -A
at '2026-11-10T10:00:00-03:00' "feat: cart and checkout"
cat > "$R/src/payments/refund.ts" <<'EOT'
import Stripe from 'stripe'

const stripe = new Stripe(process.env.STRIPE_KEY ?? '')

export async function refund(intentId: string): Promise<void> {
  await stripe.refunds.create({ payment_intent: intentId })
}
EOT
git -C "$R" add -A
at '2026-11-24T15:30:00-03:00' "feat: refunds"

